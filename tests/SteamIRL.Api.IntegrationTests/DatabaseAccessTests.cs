using System.Net;
using System.Net.Http.Json;
using System.Text.Json;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.FileProviders;
using Microsoft.Extensions.Hosting;
using Npgsql;
using SteamIRL.Api.Data;
using SteamIRL.Api.Features.Moderation;
using SteamIRL.Api.Features.Sessions;
using Xunit;

namespace SteamIRL.Api.IntegrationTests;

public sealed class DatabaseAccessTests(DatabaseAccessFixture fixture) : IClassFixture<DatabaseAccessFixture>
{
    private static string Password() => "Aa1" + Convert.ToHexString(System.Security.Cryptography.RandomNumberGenerator.GetBytes(24));
    private async Task<(HttpClient Client, Guid Id)> Register()
    {
        var client = fixture.Factory.CreateClient();
        using var response = await Send(client, "/api/auth/register", new { email = $"access-{Guid.NewGuid():N}@example.invalid", password = Password(), displayName = "[QA] Ограниченный доступ" });
        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        using var data = JsonDocument.Parse(await response.Content.ReadAsStringAsync()); return (client, data.RootElement.GetProperty("id").GetGuid());
    }
    private static async Task<HttpResponseMessage> Send(HttpClient client, string path, object body)
    {
        using var token = JsonDocument.Parse(await client.GetStringAsync("/api/auth/csrf"));
        using var request = new HttpRequestMessage(HttpMethod.Post, path) { Content = JsonContent.Create(body, options: MutationResult.JsonOptions) };
        request.Headers.Add("X-CSRF-TOKEN", token.RootElement.GetProperty("token").GetString()); request.Headers.Add("Idempotency-Key", Guid.NewGuid().ToString("N"));
        return await client.SendAsync(request);
    }
    private static async Task<object?> Query(string connectionString, string sql)
    { await using var connection = new NpgsqlConnection(connectionString); await connection.OpenAsync(); await using var command = new NpgsqlCommand(sql, connection); return await command.ExecuteScalarAsync(); }

    [Fact]
    public async Task Runtime_login_passes_guard_and_admin_or_owner_login_is_rejected()
    {
        await DatabaseAccess.VerifyApplication(fixture.AppConnection);
        await Assert.ThrowsAsync<InvalidOperationException>(() => DatabaseAccess.VerifyApplication(fixture.DatabaseAdminConnection));
        await Assert.ThrowsAsync<InvalidOperationException>(() => DatabaseAccess.VerifyApplication(fixture.MigratorConnection));
        Assert.Equal(false, await Query(fixture.AppConnection, "SELECT rolsuper OR rolcreatedb OR rolcreaterole OR rolbypassrls FROM pg_roles WHERE rolname=current_user"));
    }
    [Fact]
    public async Task Bootstrap_upgrades_existing_table_and_owned_sequence_without_granting_it_to_application()
    {
        await Query(fixture.DatabaseAdminConnection, "CREATE TABLE public.assessment_legacy (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
        await DatabaseAccess.Bootstrap(fixture.DatabaseAdminConnection, fixture.Config);
        await DatabaseAccess.Grant(fixture.MigratorConnection, fixture.Config);
        Assert.Equal(DatabaseAccess.Roles(fixture.Config).Migrator, await Query(fixture.DatabaseAdminConnection, "SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid='public.assessment_legacy'::regclass"));
        Assert.Equal(false, await Query(fixture.AppConnection, "SELECT has_table_privilege(current_user,'public.assessment_legacy','SELECT')"));
        await DatabaseAccess.VerifyApplication(fixture.AppConnection);
    }
    [Theory]
    [InlineData("CREATE TABLE public.forbidden_table(id int)")]
    [InlineData("CREATE ROLE forbidden_role")]
    [InlineData("UPDATE public.\"AspNetUserRoles\" SET \"RoleId\"=\"RoleId\"")]
    [InlineData("DELETE FROM public.moderation_decisions")]
    [InlineData("TRUNCATE public.sessions CASCADE")]
    public async Task Runtime_cannot_change_schema_roles_or_destroy_history(string sql)
    {
        var error = await Assert.ThrowsAsync<PostgresException>(() => Query(fixture.AppConnection, sql));
        Assert.Equal(PostgresErrorCodes.InsufficientPrivilege, error.SqlState);
    }
    [Fact]
    public async Task Masked_reader_has_views_but_no_private_tables_or_mutations()
    {
        using var client = (await Register()).Client;
        Assert.Equal("***@***", await Query(fixture.ReaderConnection, "SELECT email_masked FROM reporting.account_directory LIMIT 1"));
        Assert.Equal(6L, await Query(fixture.ReaderConnection, "SELECT count(*) FROM reporting.location_catalogue WHERE location_id IN ('aaaa1111-1111-4111-8111-111111111111','aaaa2222-2222-4222-8222-222222222222')"));
        foreach (var sql in new[] { "SELECT \"Email\" FROM public.\"AspNetUsers\"", "SELECT * FROM public.content_reports", "SELECT * FROM public.moderation_decisions", "DELETE FROM public.sessions" })
        {
            var error = await Assert.ThrowsAsync<PostgresException>(() => Query(fixture.ReaderConnection, sql));
            Assert.Equal(PostgresErrorCodes.InsufficientPrivilege, error.SqlState);
        }
        Assert.Equal(false, await Query(fixture.ReaderConnection, "SELECT has_table_privilege(current_user,'reporting.account_directory','DELETE')"));
        Assert.Equal(0L, await Query(fixture.ReaderConnection, "SELECT count(*) FROM information_schema.columns WHERE table_schema='reporting' AND (column_name ILIKE '%password%' OR column_name ILIKE '%security%')"));
    }
    [Fact]
    public async Task Full_moderation_and_game_flow_runs_with_application_privileges()
    {
        var actor = await Register(); using var client = actor.Client;
        using var administrative = new ApiFactory(fixture.MigratorConnection);
        await ModeratorAccess.ChangeRole(administrative.Services, actor.Id, true);
        using var proposal = await Send(client, "/api/location-submissions", new SubmissionRequest($"[QA] права {Guid.NewGuid():N}", "Тестовый ориентир", 54.7m, 25.3m, [Guid.Parse("11111111-1111-4111-8111-111111111111")]));
        Assert.Equal(HttpStatusCode.Created, proposal.StatusCode);
        var item = (await proposal.Content.ReadFromJsonAsync<SubmissionResponse>(MutationResult.JsonOptions))!;
        using var decision = await Send(client, $"/api/moderation/submissions/{item.Id}/decision", new DecisionRequest(ModerationAction.Approve, "Проверка запуска под ограниченным пользователем")); Assert.Equal(HttpStatusCode.OK, decision.StatusCode);
        using var gameResponse = await Send(client, "/api/sessions", new CreateSessionRequest(item.LocationId, item.Proposed.ActivityIds[0], SessionKind.Planned, SkillLevel.Intermediate, 1, EquipmentStatus.NotSpecified, DateTimeOffset.UtcNow.AddHours(1), DateTimeOffset.UtcNow.AddHours(2)));
        Assert.Equal(HttpStatusCode.Created, gameResponse.StatusCode);
        var game = (await gameResponse.Content.ReadFromJsonAsync<SessionResponse>(MutationResult.JsonOptions))!;
        using var participant = (await Register()).Client;
        Assert.Equal(HttpStatusCode.OK, (await Send(participant, $"/api/sessions/{game.Id}/join", new { })).StatusCode);
        Assert.Equal(HttpStatusCode.OK, (await Send(participant, $"/api/sessions/{game.Id}/leave", new { })).StatusCode);
        Assert.Equal(HttpStatusCode.OK, (await Send(client, $"/api/sessions/{game.Id}/cancel", new { })).StatusCode);
        Assert.Equal(HttpStatusCode.OK, (await client.GetAsync("/health/ready")).StatusCode);
    }
    [Theory]
    [InlineData("UPDATE public.moderation_decisions SET \"Reason\"='Changed after final decision'")]
    [InlineData("DELETE FROM public.moderation_decisions")]
    [InlineData("TRUNCATE public.moderation_decisions")]
    public async Task Database_trigger_protects_audit_even_from_accidental_owner_changes(string sql)
    {
        var actor = await Register(); using var client = actor.Client;
        using var administrative = new ApiFactory(fixture.MigratorConnection);
        await ModeratorAccess.ChangeRole(administrative.Services, actor.Id, true);
        using var report = await Send(client, "/api/content-reports", new ReportRequest(ReportReason.Other, LocationId: Guid.Parse("aaaa1111-1111-4111-8111-111111111111")));
        var item = (await report.Content.ReadFromJsonAsync<ReportResponse>(MutationResult.JsonOptions))!;
        using var decision = await Send(client, $"/api/moderation/reports/{item.Id}/decision", new DecisionRequest(ModerationAction.Resolve, "Проверка сохранности истории решений")); Assert.Equal(HttpStatusCode.OK, decision.StatusCode);
        var error = await Assert.ThrowsAsync<PostgresException>(() => Query(fixture.MigratorConnection, sql)); Assert.Equal("55000", error.SqlState);
    }
    [Fact]
    public async Task Demo_is_idempotent_and_requires_explicit_local_database_and_flag()
    {
        using var factory = new ApiFactory(fixture.MigratorConnection);
        var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?> { ["Demo:AllowSeed"] = "true", ["Demo:Password"] = Password() }).Build();
        await Assert.ThrowsAsync<InvalidOperationException>(() => DemoData.Seed(factory.Services, new DemoEnvironment("Production"), config));
        await DemoData.Seed(factory.Services, new DemoEnvironment("Development"), config);
        await DemoData.Seed(factory.Services, new DemoEnvironment("Development"), config);
        Assert.Equal(1L, await Query(fixture.MigratorConnection, "SELECT count(*) FROM public.sessions WHERE \"Id\"='eeee3333-3333-4333-8333-333333333333'"));
        Assert.Equal(1L, await Query(fixture.MigratorConnection, "SELECT count(*) FROM public.participations WHERE \"SessionId\"='eeee3333-3333-4333-8333-333333333333'"));
    }
    private sealed class DemoEnvironment(string name) : IHostEnvironment
    {
        public string EnvironmentName { get; set; } = name;
        public string ApplicationName { get; set; } = "DemoTest";
        public string ContentRootPath { get; set; } = AppContext.BaseDirectory;
        public IFileProvider ContentRootFileProvider { get; set; } = new NullFileProvider();
    }
}
